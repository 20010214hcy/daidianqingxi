async function main() {
  for (const w of weeks) {
    const content = w.items
      .map(
        ([t, p], i) =>
          `<p><strong>${i + 1}. ${t}</strong></p>\n<p>${p}</p>\n<p>&nbsp;</p>`
      )
      .join('\n')

    const exist = await prisma.article.findFirst({ where: { title: w.title } })
    if (exist) {
      console.log('skip', w.title.slice(0, 30))
      continue
    }

    await prisma.article.create({
      data: {
        title: w.title,
        content,
        summary: w.items[0][0],
        coverImage: COVER,
        authorId: 1,
        category: 'news',
        status: 'published',
        publishedAt: new Date(w.publishedAt),
        viewCount: 0,
        updatedAt: new Date(),
      },
    })
    console.log('created', w.title)
  }

  const count = await prisma.article.count()
  console.log('total articles', count)
  await prisma.$disconnect()
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
